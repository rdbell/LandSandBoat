inline auto PlanFromEquipped(const std::vector<EquippedPiece>& pieces, const std::uint8_t playerLevel) -> std::vector<ModGrant>
{
    const auto& itemToSet = ItemToSetIDs();
    const auto& metas     = SetMetas();
    std::unordered_map<std::uint16_t, int> counts;
    for (const auto& p : pieces)
    {
        const auto it = itemToSet.find(p.itemID);
        if (it == itemToSet.end() || playerLevel < p.reqLvl)
        {
            continue;
        }
        for (const auto setID : it->second)
        {
            counts[setID]++;
        }
    }
    std::vector<std::uint16_t> ids;
    ids.reserve(counts.size());
    for (const auto& kv : counts)
    {
        ids.push_back(kv.first);
    }
    std::sort(ids.begin(), ids.end());
    std::vector<ModGrant> grants;
    for (const auto setID : ids)
    {
        const auto mit = metas.find(setID);
        if (mit == metas.end())
        {
            continue;
        }
        const auto& meta  = mit->second;
        const int   count = counts[setID];
        const int   minEq = ResolvedMin(meta);
        if (count < minEq)
        {
            continue;
        }
        int clamped = std::min(count, ResolvedMax(meta));
        const int modTierIndex = clamped - minEq;
        for (const auto& row : meta.mods)
        {
            if (modTierIndex < 0 || modTierIndex >= static_cast<int>(row.values.size()))
            {
                continue;
            }
            grants.push_back(ModGrant{ static_cast<std::uint8_t>(setID), row.modID, row.values[static_cast<std::size_t>(modTierIndex)] });
        }
    }
    return grants;
}
