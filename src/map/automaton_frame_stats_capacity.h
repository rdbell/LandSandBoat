constexpr auto FrameIndex(const std::uint8_t frame) -> std::optional<std::uint8_t>
{
    switch (frame)
    {
        case FrameHarlequin:
            return 0;
        case FrameValoredge:
            return 1;
        case FrameSharpshot:
            return 2;
        case FrameStormwaker:
            return 3;
        default:
            return std::nullopt;
    }
}

constexpr auto CapStatsLevel(const std::uint8_t mlvl) -> std::uint8_t
{
    return mlvl > 99 ? 99 : mlvl;
}

inline auto StatsAtLevel(const std::uint8_t frame, const std::uint8_t level) -> std::optional<FrameLevelStats>
{
    const auto idx = FrameIndex(frame);
    if (!idx || level == 0)
    {
        return std::nullopt;
    }
    const auto lvl = CapStatsLevel(level);
    return FrameStatsTable[*idx][lvl];
}

