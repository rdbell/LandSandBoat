local wamouracampa = require('scripts/mixins/families/wamouracampa')

describe('Wamouracampa mixin', function()
    it('uses strict stance timers, damage/baseline curling, and eclosion admission', function()
        assert(xi.mix.wamouracampa.canUseEclosion(100, { 101 }))
        assert(not xi.mix.wamouracampa.canUseEclosion(100, { 102 }))
        local reset = xi.mix.wamouracampa.resetPlan(100, 45, 900, 1000)
        assert(reset.formTimeEngaged == 145 and reset.hitPoints == 700)
        assert(not xi.mix.wamouracampa.shouldStretch(5, 100, 100, 99, 700, 900))
        assert(xi.mix.wamouracampa.shouldStretch(5, 101, 100, 99, 700, 900))
        assert(not xi.mix.wamouracampa.shouldCurl(100, 100, 51, 1000, 700, 900))
        assert(xi.mix.wamouracampa.shouldCurl(101, 100, 51, 1000, 700, 900))
        assert(xi.mix.wamouracampa.shouldCurl(101, 100, 0, 1000, 900, 899))
        assert(xi.mix.wamouracampa.roamAction(4, 101, 100) == 'curl')
        assert(xi.mix.wamouracampa.roamAction(5, 101, 100) == 'stretch')
        assert(xi.mix.wamouracampa.shouldEclose(100, 100))
        assert(not xi.mix.wamouracampa.shouldEclose(0, 100))
    end)
end)
